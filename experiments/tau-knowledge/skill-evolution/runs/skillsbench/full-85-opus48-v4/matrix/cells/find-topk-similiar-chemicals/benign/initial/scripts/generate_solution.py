#!/usr/bin/env python3
"""Write the reusable solution source to the task deliverable path.

Stdin  (JSON, optional): {"output_path": "/root/workspace/solution.py"}
Stdout (JSON):           {"written": "<path>", "bytes": <int>}

The content comes from references/solution_source.py in this package, so the
deliverable is always generated by the Skill rather than hand-edited in place.
"""
import json
import os
import sys


def main():
    raw = sys.stdin.read().strip()
    cfg = {}
    if raw:
        try:
            cfg = json.loads(raw)
        except Exception:
            cfg = {}
    out_path = cfg.get("output_path") or "/root/workspace/solution.py"

    here = os.path.dirname(os.path.abspath(__file__))
    src_path = os.path.join(here, "..", "references", "solution_source.py")
    src_path = os.path.normpath(src_path)
    with open(src_path, "r", encoding="utf-8") as fh:
        content = fh.read()

    out_dir = os.path.dirname(out_path)
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write(content)

    print(json.dumps({"written": out_path, "bytes": len(content.encode("utf-8"))}))


if __name__ == "__main__":
    main()
