#!/usr/bin/env python3
"""Generate a small Atheris fuzz driver for one known local public API.

Input JSON:
  library_root: project directory
  module: importable target module, e.g. package.parser
  callable: dotted callable attribute within that module, e.g. loads
  arguments: list selected from text, bytes, int, float, bool, json_value
  output: optional driver filename, default <library_root>/fuzz.py
Output JSON reports the written file and selected target.
"""
import json
import re
import sys
from pathlib import Path

IDENT = re.compile(r"^[A-Za-z_]\w*$")
VALID_KINDS = {"text", "bytes", "int", "float", "bool", "json_value"}

TEMPLATE = '''#!/usr/bin/env python3
# Generated by python-atheris-continuous-fuzzing. Review target/signature in notes_for_testing.txt.
import sys
import json
import atheris

# Import target code while Atheris import instrumentation is active.
with atheris.instrument_imports():
    import importlib
    _target_module = importlib.import_module({module!r})

_target = _target_module
for _attribute in {attributes!r}:
    _target = getattr(_target, _attribute)


def _argument(kind, fdp):
    if kind == "text":
        return fdp.ConsumeUnicodeNoSurrogates(4096)
    if kind == "bytes":
        return fdp.ConsumeBytes(4096)
    if kind == "int":
        return fdp.ConsumeIntInRange(-(2 ** 31), 2 ** 31 - 1)
    if kind == "float":
        return fdp.ConsumeFloat()
    if kind == "bool":
        return fdp.ConsumeBool()
    if kind == "json_value":
        # A compact deterministic structured value for APIs that require a JSON-like object.
        return {{"text": fdp.ConsumeUnicodeNoSurrogates(256),
                "number": fdp.ConsumeIntInRange(-100000, 100000),
                "flag": fdp.ConsumeBool()}}
    raise ValueError("unsupported fuzz argument kind: %r" % (kind,))


@atheris.instrument_func
def TestOneInput(data: bytes):
    fdp = atheris.FuzzedDataProvider(data)
    args = [_argument(kind, fdp) for kind in {arguments!r}]
    try:
        _target(*args)
    # Refine this to the target API's documented malformed-input exceptions when known.
    # Do not catch BaseException: signals and interpreter termination must remain visible.
    except Exception:
        pass


if __name__ == "__main__":
    atheris.Setup(sys.argv, TestOneInput)
    atheris.Fuzz()
'''


def main() -> int:
    try:
        request = json.load(sys.stdin)
        root = Path(request["library_root"]).resolve()
        if not root.is_dir():
            raise ValueError("library_root is not a directory")
        module = request["module"]
        callable_name = request["callable"]
        if not isinstance(module, str) or not module or not all(IDENT.match(x) for x in module.split(".")):
            raise ValueError("module must be a dotted Python identifier")
        if not isinstance(callable_name, str) or not callable_name or not all(IDENT.match(x) for x in callable_name.split(".")):
            raise ValueError("callable must be dotted Python attributes")
        arguments = request.get("arguments", ["text"])
        if not isinstance(arguments, list) or not arguments or any(kind not in VALID_KINDS for kind in arguments):
            raise ValueError("arguments must be a nonempty list of supported kinds")
        output = Path(request.get("output", root / "fuzz.py")).resolve()
        content = TEMPLATE.format(module=module, attributes=callable_name.split("."), arguments=arguments)
        output.write_text(content, encoding="utf-8")
        try:
            output.chmod(output.stat().st_mode | 0o111)
        except OSError:
            pass
        print(json.dumps({"output": str(output), "module": module, "callable": callable_name,
                          "arguments": arguments}, indent=2))
        return 0
    except Exception as exc:
        print(json.dumps({"error": str(exc)}, indent=2))
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
